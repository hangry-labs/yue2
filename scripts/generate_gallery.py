"""Generate the public listening gallery in an isolated local CUDA container."""
import argparse
from array import array
from datetime import datetime, timezone
from email import policy
from email.parser import BytesParser
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys
import time
from urllib.error import URLError
from urllib.request import Request, urlopen
import uuid

ROOT = Path(__file__).resolve().parents[1]
GALLERY = ROOT / 'examples'
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from scripts.audio_formats import convert, profile


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def write_json(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    temp = path.with_suffix(path.suffix + '.tmp')
    temp.write_text(json.dumps(value, ensure_ascii=False, indent=2) + '\n', encoding='utf-8', newline='\n')
    temp.replace(path)


def http_json(base, path, body=None):
    request = Request(base + path, data=canonical(body) if body is not None else None,
                      headers={'Content-Type': 'application/json'})
    with urlopen(request, timeout=30) as response:
        return json.load(response)


def models():
    manifest = json.loads((ROOT / 'docker/models.json').read_text(encoding='utf-8'))
    result = []
    for name in ('YuE2-3B-Q8_0.gguf', 'YuE2-Vae-F32.gguf'):
        path = ROOT / 'data/models' / name
        if not path.is_file():
            raise ValueError(f'Missing {path.relative_to(ROOT)}; run task models first.')
        measured = {'file': name, 'bytes': path.stat().st_size, 'sha256': digest(path)}
        expected = manifest['files'][name]
        if measured['bytes'] != expected['size'] or measured['sha256'] != expected['sha256']:
            raise ValueError(f'{name} does not match the pinned model manifest.')
        result.append(measured)
    # Keep the publisher's pinned source alongside the measured file identities.
    return {'files': result, 'publisher_manifest': manifest}


def run_job(base, request):
    job = http_json(base, '/synth', request)['id']
    started = time.monotonic()
    while True:
        status = http_json(base, '/job?id=' + job)['status']
        if status == 'done':
            break
        if status in ('failed', 'cancelled'):
            raise RuntimeError(f'Gallery job {job} {status}; inspect its container logs.')
        if time.monotonic() - started > 1200:
            http_json(base, '/job?id=' + job + '&cancel=1', {})
            raise TimeoutError(f'Gallery job {job} exceeded 20 minutes.')
        time.sleep(1)
    with urlopen(base + '/job?id=' + job + '&result=1', timeout=60) as response:
        content_type = response.headers['Content-Type']
        message = BytesParser(policy=policy.default).parsebytes(
            ('Content-Type: ' + content_type + '\r\nMIME-Version: 1.0\r\n\r\n').encode()
            + response.read())
    parts = list(message.iter_parts())
    replay = next(json.loads(part.get_payload(decode=True)) for part in parts
                  if part.get_content_type() == 'application/json')
    audio = next(part.get_payload(decode=True) for part in parts
                 if part.get_content_type().startswith('audio/'))
    return job, replay, audio, round(time.monotonic() - started, 2)


def probe(path):
    result = subprocess.run(['ffprobe', '-v', 'error', '-show_entries',
                             'format=duration:stream=codec_name,sample_rate,channels',
                             '-of', 'json', str(path)], check=True, capture_output=True,
                            encoding='utf-8')
    info = json.loads(result.stdout)
    stream = info['streams'][0]
    if stream['codec_name'] != 'mp3' or int(stream['sample_rate']) != 48000 or stream['channels'] != 2:
        raise ValueError(f'Unexpected generated audio format: {info}')
    return {'seconds': round(float(info['format']['duration']), 3),
            'sample_rate': 48000, 'channels': 2, 'codec': 'mp3'}


def waveform(path):
    samples = array('f')
    decoded = subprocess.run(['ffmpeg', '-v', 'error', '-i', str(path), '-ac', '1', '-ar', '2000',
                              '-f', 'f32le', '-'], capture_output=True, check=True)
    samples.frombytes(decoded.stdout)
    if sys.byteorder != 'little':
        samples.byteswap()
    peaks = [max((abs(x) for x in samples[i * len(samples) // 96:(i + 1) * len(samples) // 96]), default=0)
             for i in range(96)]
    top = max(peaks) or 1
    return [round(peak / top, 3) for peak in peaks]


def publish(manifest):
    write_json(GALLERY / 'assets/manifest.json', manifest)
    # A classic script keeps a downloaded gallery usable through file:// as well.
    (GALLERY / 'catalog.js').write_text(
        '// Generated by scripts/generate_gallery.py. Do not edit.\n'
        + 'window.YUE2_GALLERY = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n',
        encoding='utf-8', newline='\n')


def generate(base, image, selected, force=False):
    definitions = json.loads((GALLERY / 'definitions.json').read_text(encoding='utf-8'))
    identifiers = [song['id'] for song in definitions['songs']]
    if len(identifiers) != len(set(identifiers)) or any(not re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', key) for key in identifiers):
        raise ValueError('Song IDs must be unique lowercase filename slugs.')
    props = http_json(base, '/props')
    identity = models()
    old_path = GALLERY / 'assets/manifest.json'
    old = json.loads(old_path.read_text(encoding='utf-8')) if old_path.exists() else {'songs': []}
    previous = {song['id']: song for song in old['songs']}
    output = {'schema': 3, 'definitions_sha256': hashlib.sha256(canonical(definitions)).hexdigest(),
              'engine': {'version': props['version'], 'context': props['context'], 'image': image},
              'models': identity, 'songs': []}
    for song in definitions['songs']:
        request = {**definitions['settings'], **song['request']}
        cached = previous.get(song['id'])
        if cached and not force:
            for asset in [cached[k] for k in ('audio', 'recipe', 'replay')] + list((cached.get('downloads') or {}).values()):
                path = GALLERY / asset['path']
                if path.is_file() and digest(path) != asset['sha256']:
                    raise ValueError(f'Published asset changed: {asset["path"]}; review it before regenerating.')
        recorded_engine = (cached.get('engine') or old.get('engine')) if cached else output['engine']
        fingerprint = hashlib.sha256(canonical({'song': song, 'request': request,
                                                'models': identity, 'engine': recorded_engine})).hexdigest()
        valid = cached and cached.get('fingerprint') == fingerprint and all(
            (GALLERY / asset['path']).is_file() and digest(GALLERY / asset['path']) == asset['sha256']
            for asset in [cached[k] for k in ('audio', 'recipe', 'replay')] + list((cached.get('downloads') or {}).values()))
        if valid and not (force and (not selected or song['id'] in selected)):
            print(f"Reuse: {song['title']}", flush=True)
            cached['engine'] = recorded_engine
            if not cached.get('waveform'):
                cached['waveform'] = waveform(GALLERY / cached['audio']['path'])
            replay_path = GALLERY / cached['replay']['path']
            replay = json.loads(replay_path.read_text(encoding='utf-8'))
            write_json(replay_path, {'title': song['title'], **request, **replay})
            cached['replay']['bytes'] = replay_path.stat().st_size
            cached['replay']['sha256'] = digest(replay_path)
            output['songs'].append(cached)
            publish(output)
            continue
        if selected and song['id'] not in selected:
            raise ValueError(f"No matching cached sample for {song['id']}; generate it first.")
        fingerprint = hashlib.sha256(canonical({'song': song, 'request': request,
                                                'models': identity, 'engine': output['engine']})).hexdigest()
        print(f"Generate: {song['title']} (8 steps, ceiling {request['duration']}s)", flush=True)
        job, replay, audio, wall = run_job(base, request)
        extension = '.wav' if request['output_format'].startswith('wav') else '.mp3'
        master = ROOT / 'data/results/gallery-masters' / (song['id'] + '-' + fingerprint[:12] + extension)
        master.parent.mkdir(parents=True, exist_ok=True)
        temporary = master.with_suffix(extension + '.tmp')
        temporary.write_bytes(audio)
        from scripts.audio_formats import probe as probe_master
        master_info = probe_master(temporary)
        temporary.replace(master)
        downloads = {}
        for name in ('opus',):
            audio_path = GALLERY / 'assets/music' / (song['id'] + profile(name)['extension'])
            previous_asset = (cached.get('downloads') or {}).get(name) if cached else None
            owned_output = previous_asset and previous_asset['path'] == audio_path.relative_to(GALLERY).as_posix()
            info = convert(master, audio_path, name, overwrite=force or bool(owned_output))
            downloads[name] = {'path': audio_path.relative_to(GALLERY).as_posix(), **info}
        recipe = GALLERY / 'recipes' / (song['id'] + '.json')
        replay_path = GALLERY / 'recipes' / (song['id'] + '.replay.json')
        write_json(recipe, {'title': song['title'], **request})
        write_json(replay_path, {'title': song['title'], **request, **replay})
        record = {**{k: v for k, v in song.items() if k != 'request'}, 'request': request,
                  'fingerprint': fingerprint, 'generated_at': datetime.now(timezone.utc).isoformat(),
                  'job': job, 'wall_seconds': wall, 'waveform': waveform(GALLERY / downloads['opus']['path']),
                  'engine': output['engine'], 'downloads': downloads, 'audio': downloads['opus'],
                  'master': {**master_info, 'sha256': digest(master), 'bytes': master.stat().st_size,
                             'retained_locally': True},
                  'generation_source': {**master_info, 'sha256': digest(master), 'bytes': master.stat().st_size}}
        for key, path in [('recipe', recipe), ('replay', replay_path)]:
            record[key] = {'path': path.relative_to(GALLERY).as_posix(),
                           'bytes': path.stat().st_size, 'sha256': digest(path)}
        output['songs'].append(record)
        publish(output)
        print(f"Saved: {master_info['seconds']:.1f}s source and Opus export, {wall:.1f}s wall", flush=True)
    return output


def main():
    if hasattr(sys.stdout, 'reconfigure'):
        sys.stdout.reconfigure(encoding='utf-8')
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--image', default='yue2:dev')
    parser.add_argument('--only', action='append', default=[])
    parser.add_argument('--force', action='store_true', help='Regenerate selected songs instead of reusing verified recordings')
    args = parser.parse_args()
    if not shutil.which('ffprobe'):
        parser.error('FFprobe is required to validate the generated MP3 files.')
    inspected = json.loads(subprocess.check_output(['docker', 'image', 'inspect', args.image]))[0]
    name = 'yue2-gallery-' + uuid.uuid4().hex[:8]
    command = ['docker', 'run', '-d', '--rm', '--name', name, '--gpus', 'all',
               '--label', 'io.hangrylabs.project=yue2-gallery', '-p', '127.0.0.1::8087',
               '--mount', f'type=bind,source={ROOT / "data/models"},target=/models,readonly',
               '--mount', f'type=bind,source={ROOT / "data/adapters"},target=/adapters,readonly', args.image]
    try:
        subprocess.run(command, check=True, capture_output=True)
        container = json.loads(subprocess.check_output(['docker', 'inspect', name]))[0]
        port = container['NetworkSettings']['Ports']['8087/tcp'][0]['HostPort']
        base = 'http://127.0.0.1:' + port
        for attempt in range(60):
            try:
                http_json(base, '/health')
                break
            except (URLError, ConnectionError):
                time.sleep(1)
        else:
            raise RuntimeError('The isolated gallery server did not become ready.')
        generate(base, {'tag': args.image, 'id': inspected['Id']}, args.only, args.force)
    finally:
        subprocess.run(['docker', 'rm', '-f', name], capture_output=True)


if __name__ == '__main__':
    main()
