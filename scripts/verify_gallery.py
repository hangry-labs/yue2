"""Verify public gallery definitions, recipes and exact audio bytes without a GPU."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def canonical(value):
    return json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(',', ':')).encode('utf-8')


def verify(root=ROOT):
    gallery = root / 'examples'
    definitions = json.loads((gallery / 'definitions.json').read_text(encoding='utf-8'))
    manifest = json.loads((gallery / 'assets/manifest.json').read_text(encoding='utf-8'))
    if manifest.get('schema') != 3:
        raise ValueError('Gallery must use the Opus-only manifest schema (3).')
    if manifest['definitions_sha256'] != hashlib.sha256(canonical(definitions)).hexdigest():
        raise ValueError('Gallery definitions changed; regenerate or verify the matching recordings.')
    if [s['id'] for s in manifest['songs']] != [s['id'] for s in definitions['songs']]:
        raise ValueError('Every defined song needs a completed recording, in definition order.')
    published_audio = set()
    for definition, song in zip(definitions['songs'], manifest['songs']):
        request = {**definitions['settings'], **definition['request']}
        if song['request'] != request:
            raise ValueError(f"Request mismatch: {song['id']}")
        fingerprint = hashlib.sha256(canonical({'song': definition, 'request': request,
                                                'models': manifest['models'], 'engine': song.get('engine') or manifest['engine']})).hexdigest()
        if song['fingerprint'] != fingerprint:
            raise ValueError(f"Recipe/model fingerprint mismatch: {song['id']}")
        assets = [song[key] for key in ('audio', 'recipe', 'replay')] + list((song.get('downloads') or {}).values())
        for asset in assets:
            path = (gallery / asset['path']).resolve()
            if not path.is_relative_to(gallery.resolve()) or path.is_symlink():
                raise ValueError('Gallery media must stay inside examples/.')
            with path.open('rb') as stream:
                digest = hashlib.file_digest(stream, 'sha256').hexdigest()
            if digest != asset['sha256'] or path.stat().st_size != asset['bytes']:
                raise ValueError(f'Changed published asset: {path}')
        recipe = json.loads((gallery / song['recipe']['path']).read_text(encoding='utf-8'))
        if recipe != {'title': song['title'], **request}:
            raise ValueError(f"Prompt JSON differs from its recording recipe: {song['id']}")
        replay = json.loads((gallery / song['replay']['path']).read_text(encoding='utf-8'))
        if any(replay.get(key) != request.get(key) for key in ('style', 'lyrics', 'lm_seed', 'seed', 'steps')):
            raise ValueError(f"Replay does not match the generated request: {song['id']}")
        if not replay.get('abc') or not replay.get('semantic_tokens'):
            raise ValueError(f"Replay lacks the generated score or performance: {song['id']}")
        audio = song['audio']
        if audio['codec'] != 'opus' or audio['sample_rate'] != 48000 or audio['channels'] != 2 or audio['seconds'] <= 0:
            raise ValueError(f"Unexpected audio metadata: {song['id']}")
        if set(song.get('downloads', {})) != {'opus'} or audio != song['downloads']['opus']:
            raise ValueError('Gallery playback and downloads must share one Opus asset.')
        audio_path = (gallery / audio['path']).resolve()
        if audio_path.parent != (gallery / 'assets/music').resolve() or audio_path.suffix != '.opus':
            raise ValueError('Gallery audio must be an .opus file in assets/music/.')
        published_audio.add(audio_path)
        if audio.get('encoding'):
            known_sources = {song.get('generation_source', {}).get('sha256'), song.get('master', {}).get('sha256')} - {None}
            if audio.get('source', {}).get('sha256') not in known_sources:
                raise ValueError(f"Unknown conversion source: {song['id']}")
            if audio['encoding']['codec'] != 'opus':
                raise ValueError(f"Wrong encoding recipe: {song['id']}")
        if len(song.get('waveform', [])) != 96 or any(not 0 <= n <= 1 for n in song['waveform']):
            raise ValueError(f"Missing or invalid waveform: {song['id']}")
    music_files = {path.resolve() for path in (gallery / 'assets/music').rglob('*') if path.is_file()}
    if music_files != published_audio:
        raise ValueError('Gallery music folder must contain only the referenced Opus files; remove duplicate or unreferenced exports.')
    expected_script = '// Generated by scripts/generate_gallery.py. Do not edit.\nwindow.YUE2_GALLERY = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n'
    if (gallery / 'catalog.js').read_text(encoding='utf-8') != expected_script:
        raise ValueError('Embedded gallery catalog differs from the provenance manifest.')
    print(f"PASS: {len(manifest['songs'])} gallery recordings, recipes, waveforms and SHA-256 checksums.")
    return manifest


if __name__ == '__main__':
    verify()
