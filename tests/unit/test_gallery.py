"""Public audio must remain paired with its actual definitions and recipes."""
from contextlib import redirect_stdout
import hashlib
import io
import json
from pathlib import Path
import tempfile
import unittest

from scripts.verify_gallery import canonical, verify


class GalleryIntegrityTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.root = Path(self.temp.name)
        self.gallery = self.root / 'examples'
        self.gallery.mkdir()
        request = {'style': 'piano', 'lyrics': 'Original words', 'steps': 8, 'lm_seed': 1, 'seed': 2}
        definition = {'id': 'song', 'title': 'Song', 'request': request}
        definitions = {'settings': {}, 'songs': [definition]}
        self.write('definitions.json', definitions)
        engine, models = {'version': 'test'}, {'files': []}
        record = {'id': 'song', 'title': 'Song', 'request': request, 'waveform': [0.5] * 96,
                  'fingerprint': hashlib.sha256(canonical({'song': definition, 'request': request,
                                                            'models': models, 'engine': engine})).hexdigest()}
        for name, value in [('recipe', {'title': 'Song', **request}),
                            ('replay', {**request, 'abc': 'X:1', 'semantic_tokens': '1,2'})]:
            self.write(name + '.json', value)
        (self.gallery / 'audio.mp3').write_bytes(b'integrity test bytes, not a decoded audio fixture')
        for name in ('audio', 'recipe', 'replay'):
            path = self.gallery / (name + ('.mp3' if name == 'audio' else '.json'))
            data = path.read_bytes()
            record[name] = {'path': path.name, 'bytes': len(data), 'sha256': hashlib.sha256(data).hexdigest()}
        record['audio'].update(codec='mp3', sample_rate=48000, channels=2, seconds=1)
        manifest = {'definitions_sha256': hashlib.sha256(canonical(definitions)).hexdigest(),
                    'engine': engine, 'models': models, 'songs': [record]}
        self.write('assets/manifest.json', manifest)
        self.catalog = '// Generated by scripts/generate_gallery.py. Do not edit.\nwindow.YUE2_GALLERY = ' + json.dumps(manifest, ensure_ascii=False, indent=2) + ';\n'
        (self.gallery / 'catalog.js').write_text(self.catalog, encoding='utf-8')

    def write(self, name, value):
        path = self.gallery / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(value), encoding='utf-8')

    def test_valid_manifest_checks_exact_files(self):
        with redirect_stdout(io.StringIO()):
            self.assertEqual(len(verify(self.root)['songs']), 1)

    def test_changed_audio_is_rejected(self):
        (self.gallery / 'audio.mp3').write_bytes(b'other audio bytes')
        with self.assertRaisesRegex(ValueError, 'Changed published asset'):
            verify(self.root)

    def test_edited_definition_requires_its_matching_recording(self):
        value = json.loads((self.gallery / 'definitions.json').read_text())
        value['songs'][0]['request']['lyrics'] = 'Different words'
        self.write('definitions.json', value)
        with self.assertRaisesRegex(ValueError, 'definitions changed'):
            verify(self.root)

    def test_browser_catalog_cannot_drift_from_manifest(self):
        (self.gallery / 'catalog.js').write_text(self.catalog.replace('Original words', 'Stale words'))
        with self.assertRaisesRegex(ValueError, 'catalog differs'):
            verify(self.root)
